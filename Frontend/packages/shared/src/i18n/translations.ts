export const dictionaries: Record<Lang, Partial<Record<TKey, string>>> = { en, rw, fr }

export function translate(lang: Lang, key: TKey): string {
  return dictionaries[lang][key] ?? en[key]
}

/** Fills placeholders like {n} in a translated string: fill(t('learn.questionOf'), { n: 1, total: 5 }). */
export function fill(text: string, values: Record<string, string | number>) {
  return text.replace(/\{(\w+)\}/g, (match, name: string) => (name in values ? String(values[name]) : match))
}
