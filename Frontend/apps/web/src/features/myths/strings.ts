const STRINGS: Record<Lang, Strings> = { en, rw, fr }

/** The page's text in the chosen language, plus a helper to fill in {n}, {total}, {name}. */
export function useMythStrings() {
  const { lang } = useLanguage()
  const s = STRINGS[lang] ?? en
  const f = (text: string, values: Record<string, string | number>) =>
    text.replace(/\{(\w+)\}/g, (_, k: string) => String(values[k] ?? ''))
  const levelName = (index: number) => [s.level0, s.level1, s.level2][index] ?? s.level0
  return { s, f, levelName }
}
